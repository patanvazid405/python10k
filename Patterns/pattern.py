print("rombus star pattern")
n = 5
for i in range(1,n+1):
    spc=" "*(n-i)
    st = "* "*i
    print(spc+st)
for j in range(n,0,-1):
    spc=" "*(n-j)
    st = "* "*j
    print(spc+st)

